def clean_dataframe(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()

    # 如果 Excel 被错误读取成“第一行是字段名、真正表头在数据行”，自动重新识别表头。
    expected = {"phos_1_type", "apo_type", "Size_Mean_nm", "PDI", "EE_Percent"}
    normalized_cols = [_normalize_column_name(c) for c in df.columns]
    if len(expected.intersection(set(normalized_cols))) < 2 and len(df) > 0:
        max_scan_rows = min(8, len(df))
        for i in range(max_scan_rows):
            candidate = [_normalize_column_name(v) for v in df.iloc[i].tolist()]
            if len(expected.intersection(set(candidate))) >= 2:
                df = df.iloc[i + 1:].reset_index(drop=True)
                df.columns = candidate
                break

    df.columns = _deduplicate_columns([_normalize_column_name(c) for c in df.columns])
    df = df.loc[:, ~pd.Index(df.columns).astype(str).str.startswith("Unnamed")]
    df = df.dropna(axis=1, how="all")

    for col in df.columns:
        if df[col].dtype == "object":
            df[col] = df[col].astype(str).str.strip()
            df[col] = df[col].replace({
                "": None,
                "nan": None,
                "NaN": None,
                "None": None,
                "none": None,
                "NULL": None,
                "null": None,
                "NA": None,
                "N/A": None,
            })

    # 只转换真正的数值字段。不能用 "ph" 这类宽泛关键字，否则 phos_1_type 会被误判为数值列，
    # DMPC / POPC 等磷脂名称会被强制转成 NaN，最终导致图表提示“字段暂无有效数据”。
    def _is_numeric_data_column(col_name: str) -> bool:
        lc = str(col_name).strip().lower()

        # 明确保护文本/分类字段
        if lc in {"ref_id", "formulation_name", "ratio_metric"}:
            return False
        if lc.endswith("_type") or lc.endswith("_name"):
            return False
        if any(token in lc for token in ["method", "buffer", "shape", "indication", "phase", "ligand", "has_"]):
            return False

        # 明确数值字段
        exact_numeric = {
            "pdi",
            "zeta_mv",
            "size_mean_nm",
            "ee_percent",
            "dl_percent",
            "ph_assembly",
            "num_thermal_cycles",
        }
        if lc in exact_numeric:
            return True

        numeric_suffixes = (
            "_ratio",
            "_pct",
            "_percent",
            "_c",
            "_h",
            "_nm",
            "_mv",
        )
        if lc.endswith(numeric_suffixes):
            return True

        numeric_prefixes = (
            "temp_",
            "time_",
            "num_",
            "flux",
        )
        if lc.startswith(numeric_prefixes):
            return True

        return False

    numeric_hint_cols = [col for col in df.columns if _is_numeric_data_column(str(col))]

    for col in set(numeric_hint_cols):
        try:
            if df[col].dtype == "object":
                df[col] = (
                    df[col]
                    .astype(str)
                    .str.replace("−", "-", regex=False)
                    .str.replace("–", "-", regex=False)
                    .str.replace("%", "", regex=False)
                    .str.extract(r"([-+]?\d*\.?\d+)", expand=False)
                )
            df[col] = pd.to_numeric(df[col], errors="coerce")
        except Exception:
            pass

    return df


