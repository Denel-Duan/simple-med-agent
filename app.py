def _deduplicate_columns(columns: List[str]) -> List[str]:
    counts: Dict[str, int] = {}
    out: List[str] = []
    for col in columns:
        base = str(col).strip() or "column"
        if base not in counts:
            counts[base] = 0
            out.append(base)
        else:
            counts[base] += 1
            out.append(f"{base}_{counts[base]}")
    return out


